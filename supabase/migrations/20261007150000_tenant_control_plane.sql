 attempt INTEGER NOT NULL DEFAULT 0, created_at DOUBLE PRECISION NOT NULL,
 updated_at DOUBLE PRECISION NOT NULL,
 FOREIGN KEY(owner_id,task_id) REFERENCES tasks(owner_id,task_id),
 FOREIGN KEY(session_id) REFERENCES engine_sessions(session_id)
);
ALTER TABLE worker_jobs ENABLE ROW LEVEL SECURITY;
