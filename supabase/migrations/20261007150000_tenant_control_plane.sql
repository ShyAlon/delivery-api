 job_id TEXT PRIMARY KEY, owner_id UUID NOT NULL REFERENCES auth.users(id),
 auth_session_id UUID NOT NULL, task_id TEXT NOT NULL, session_id TEXT NOT NULL,
 generation INTEGER NOT NULL CHECK(generation>0), kind TEXT NOT NULL,
