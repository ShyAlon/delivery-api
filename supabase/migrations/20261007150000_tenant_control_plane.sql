CREATE POLICY tenant_isolation ON worker_jobs TO authenticated
 USING (public.requi_session_active() AND owner_id=auth.uid())
 WITH CHECK (public.requi_session_active() AND owner_id=auth.uid() AND
   EXISTS(SELECT 1 FROM engine_sessions s WHERE s.session_id=worker_jobs.session_id
    AND s.owner_id=worker_jobs.owner_id AND s.task_id=worker_jobs.task_id
    AND s.generation=worker_jobs.generation));
GRANT SELECT,INSERT,UPDATE,DELETE ON worker_jobs TO authenticated;
