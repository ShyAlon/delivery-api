-- Supabase session presence closes copied-JWT access after sign-out. This
-- narrow definer reveals only whether THIS signed subject/session still exists.
CREATE FUNCTION public.requi_session_active() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT EXISTS (SELECT 1 FROM auth.sessions s
 WHERE s.id=COALESCE(nullif(current_setting('request.jwt.claim.session_id',true),''),
   nullif(current_setting('request.jwt.claims',true),'')::jsonb ->> 'session_id')::uuid
   AND s.user_id=auth.uid());
$$;
REVOKE ALL ON FUNCTION public.requi_session_active() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.requi_session_active() TO authenticated;
