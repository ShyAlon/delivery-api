-- User quota/profile creation is a provisioning operation. A user cannot buy
-- themselves quota by changing their own profile through the database API.
REVOKE INSERT, UPDATE, DELETE ON users FROM authenticated;
-- Auth-created users get a zero-quota profile. No user-editable metadata drives
-- roles or credits. Quota allocation belongs to the later controlled spend stage.
CREATE FUNCTION public.requi_profile_created() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 INSERT INTO public.users(user_id,label,created_at,updated_at)
 VALUES (NEW.id,'Signed-In User',extract(epoch FROM clock_timestamp()),extract(epoch FROM clock_timestamp()));
 RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.requi_profile_created() FROM PUBLIC;
CREATE TRIGGER requi_profile_after_signup AFTER INSERT ON auth.users
 FOR EACH ROW EXECUTE FUNCTION public.requi_profile_created();
