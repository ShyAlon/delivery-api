"""Re-reads the two DeepSeek pages and builds the reviewed price and context-ceiling settings. Public GETs only, never a provider call."""
import datetime,decimal,hashlib,json,os,sys
from decimal import Decimal
from delivery_api import vendor_sources as vs,retail_pricing,production_gateway as pg
MODEL='deepseek-flash';CONTEXT=128000;MAX_OUT=16384
out=sys.argv[1]
def die(why):
    print('PIN-FAIL '+why);sys.exit(2)
try:
    bodies={u:vs.fetch_verified_source(u) for u in (vs.PRICING_URL,vs.API_URL)}
except Exception as exc:die('cannot read the vendor pages: %s: %s'%(type(exc).__name__,str(exc)[:200]))
try:parsed=vs.parse(bodies[vs.PRICING_URL],bodies[vs.API_URL],MODEL)
except vs.SourceChanged as exc:die('the published table no longer matches what the parser accepts: %s'%exc)
now=datetime.datetime.now(datetime.timezone.utc)
snapshot={k:parsed[k] for k in ('model','model_version','published_usd_per_million','published_period_rule','raw_context_limit','raw_output_limit','context_proposal')}
snapshot['parser_version']='deepseek-html-v2';snapshot['fetched_at']=now.isoformat()
snapshot['sources']=[{'url':u,'sha256':hashlib.sha256(b.encode()).hexdigest()} for u,b in bodies.items()]
vendor_ctx={'K':1000,'M':1000000}[parsed['raw_context_limit'][-1]]*Decimal(parsed['raw_context_limit'][:-1])
vendor_out=parsed['context_proposal']['maximum_output_tokens']
if CONTEXT>vendor_ctx:die('reviewed context %d is above the vendor limit %s'%(CONTEXT,parsed['raw_context_limit']))
if MAX_OUT>vendor_out:die('reviewed max output %d is above the vendor limit %d'%(MAX_OUT,vendor_out))
d=retail_pricing.DEFAULTS;scale=10**9
per_token=Decimal(d['PRICE_PER_TOKEN'])*scale
if per_token!=int(per_token):die('retail price per token is not a whole number of units')
version='%s-%s'%(MODEL,now.strftime('%Y%m%d'))
peak=parsed['catalog_proposals']['peak'][0]
row={'provider':'deepseek','model':MODEL,'price_version':version,'source':vs.PRICING_URL,
    'expense_input':peak['expense_cache_miss'],'expense_cache_hit':peak['expense_cache_hit'],'expense_cache_miss':peak['expense_cache_miss'],'expense_output':peak['expense_output'],
    'expense_units_per_usd':peak['expense_units_per_usd'],'retail_input':int(per_token),'retail_output':int(per_token),'retail_units_per_credit':scale,
    'usage_categories':peak['usage_categories'],
    'retail_formula':{'formula_version':'tokens-plus-compute-v1','units_per_credit':scale,'price_per_token':d['PRICE_PER_TOKEN'],'price_per_10ms':d['PRICE_PER_10MS'],'usd_per_credit':d['USD_PER_CREDIT']},
    'provider_snapshot':snapshot}
ceiling={'model':MODEL,'context_tokens':CONTEXT,'maximum_output_tokens':MAX_OUT,'source':vs.PRICING_URL+' ; '+vs.API_URL+' ; owner confirmation 2026-10-17 20:02','bound_version':version,'protective_run_ceiling':True}
env={pg.PRICES_ENV:json.dumps([row],separators=(',',':'),sort_keys=True),pg.CEILING_ENV:json.dumps(ceiling,separators=(',',':'),sort_keys=True),pg.KEY_ENV:'placeholder-not-written'}
# The same checks the server runs, offline against the pages just read.
try:
    factory=pg.gateways_from_environment(None,env,vendor_fetcher=lambda u:bodies[u]);factory.close()
    vs.verify_current_sources(snapshot,lambda u:bodies[u],cached=False,log=lambda t:None)
except Exception as exc:die('the server would refuse these settings: %s: %s'%(type(exc).__name__,str(exc)[:300]))
for u,b in bodies.items():
    open(os.path.join(out,'page-'+hashlib.sha256(u.encode()).hexdigest()[:8]+'.html'),'w').write(b)
text='# Reviewed vendor prices and context ceiling, read %s. Generated by the re-pin script; do not edit.\n%s=%s\n%s=%s\n'%(now.isoformat(),pg.PRICES_ENV,env[pg.PRICES_ENV],pg.CEILING_ENV,env[pg.CEILING_ENV])
open(os.path.join(out,'cloud-models.env'),'w').write(text)
inp=(CONTEXT-MAX_OUT);miss=Decimal(parsed['published_usd_per_million']['peak']['cache_miss']);o=Decimal(parsed['published_usd_per_million']['peak']['output'])
worst=(inp*miss+MAX_OUT*o)/10**6
r=parsed['published_usd_per_million']
print('MODEL      %s (%s)'%(MODEL,parsed['model_version']))
print('PEAK       $%s in (miss), $%s in (hit), $%s out, per 1M tokens'%(r['peak']['cache_miss'],r['peak']['cache_hit'],r['peak']['output']))
print('OFF-PEAK   $%s in (miss), $%s in (hit), $%s out, per 1M tokens'%(r['off_peak']['cache_miss'],r['off_peak']['cache_hit'],r['off_peak']['output']))
print('RULE       '+parsed['published_period_rule'][:150])
print('RETAIL     %s credits/token, %s credits/10ms, $%s/credit (from the code defaults)'%(d['PRICE_PER_TOKEN'],d['PRICE_PER_10MS'],d['USD_PER_CREDIT']))
print('CEILING    %d tokens per call, max output %d (vendor: %s context, %d output)'%(CONTEXT,MAX_OUT,parsed['raw_context_limit'],vendor_out))
print('WORST CALL about $%s provider cost at peak rates (%d in + %d out)'%(worst.quantize(Decimal('0.001')),inp,MAX_OUT))
print('READ AT    '+now.isoformat())
for s in snapshot['sources']:print('SOURCE     %s sha256 %s'%(s['url'],s['sha256'][:16]))
print('NOTE       the service re-checks these pages about hourly; a failed check or a changed term is a warning in the back office and log, and calls continue on these pinned terms')
